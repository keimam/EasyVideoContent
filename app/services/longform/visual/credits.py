"""Credits and Attribution Manager for Visual Assets (4.1).

Maintains `export/credits.txt` with formatted deduplicated citations
for stock video creators and licensed visual assets used in the project.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional

from app.services.longform.visual.base import VisualCandidate


class CreditsManager:
    """Records attribution entries in export/credits.txt without duplicates."""

    def __init__(self, project_dir: Path | str) -> None:
        self.project_dir = Path(project_dir).resolve()
        self.credits_file = self.project_dir / "export" / "credits.txt"

    def record_asset_credit(
        self,
        candidate: VisualCandidate,
        shot_id: Optional[str] = None,
    ) -> None:
        """Add or update an attribution record for a visual asset."""
        if not candidate.author and not candidate.source_url:
            return

        self.credits_file.parent.mkdir(parents=True, exist_ok=True)
        existing_lines = []
        if self.credits_file.is_file():
            existing_lines = self.credits_file.read_text(encoding="utf-8").splitlines()

        entry_key = f"[{candidate.provider.upper()}] {candidate.candidate_id}"
        for line in existing_lines:
            if entry_key in line:
                return  # already recorded

        author_str = candidate.author or "Unknown Creator"
        author_link = f" ({candidate.author_url})" if candidate.author_url else ""
        source_link = f" | URL: {candidate.source_url}" if candidate.source_url else ""
        shot_note = f" [Used in {shot_id}]" if shot_id else ""
        license_str = f" | License: {candidate.license}"

        new_entry = f"- {entry_key}{shot_note}: Creator: {author_str}{author_link}{source_link}{license_str}"

        # Write/append
        if not existing_lines:
            header = [
                "=================================================================",
                "VISUAL ASSET ATTRIBUTIONS & CREDITS",
                "Generated by MoneyPrinterTurbo Longform Engine",
                "=================================================================",
                "",
            ]
            content = "\n".join(header) + "\n" + new_entry + "\n"
        else:
            content = "\n".join(existing_lines).strip() + "\n" + new_entry + "\n"

        self.credits_file.write_text(content, encoding="utf-8")
