"""Credits and Attribution Manager for Visual & Audio Assets (4.1, D9.3).

Maintains `export/credits.txt` and `export/credits.md` with formatted deduplicated
citations for stock/CC/NASA/Wikimedia/Openverse creators and licensed assets.
"""

from __future__ import annotations

import os
import shutil
import threading
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.services.longform.visual.base import VisualCandidate, license_requires_attribution


class CreditsManager:
    """Records attribution entries in export/credits.txt and export/credits.md without duplicates."""

    def __init__(self, project_dir: Path | str) -> None:
        self.project_dir = Path(project_dir).resolve()
        self.credits_file = self.project_dir / "export" / "credits.txt"
        self.credits_md_file = self.project_dir / "export" / "credits.md"
        self._lock = threading.Lock()

    def record_asset_credit(
        self,
        candidate: VisualCandidate,
        shot_id: Optional[str] = None,
    ) -> None:
        """Add or update an attribution record for a visual asset (thread-safe atomic write)."""
        if not candidate.author and not candidate.source_url and not getattr(candidate, "title", None):
            return

        with self._lock:
            self.credits_file.parent.mkdir(parents=True, exist_ok=True)
            existing_lines = []
            if self.credits_file.is_file():
                existing_lines = self.credits_file.read_text(encoding="utf-8").splitlines()

            entry_key = f"[{candidate.provider.upper()}] {candidate.candidate_id}"
            for line in existing_lines:
                if entry_key in line:
                    return  # already recorded

            title_str = f' "{candidate.title}"' if getattr(candidate, "title", None) else ""
            author_str = candidate.author or "Unknown Creator"
            author_link = f" ({candidate.author_url})" if candidate.author_url else ""
            source_link = f" | URL: {candidate.source_url}" if candidate.source_url else ""
            shot_note = f" [Used in {shot_id}]" if shot_id else ""
            license_str = f" | License: {candidate.license}"

            new_entry = f"- {entry_key}{shot_note}:{title_str} Creator: {author_str}{author_link}{source_link}{license_str}"

            # Write/append atomically via .tmp -> os.replace
            if not existing_lines:
                header = [
                    "=================================================================",
                    "VISUAL ASSET ATTRIBUTIONS & CREDITS",
                    "Generated by EasyFaceless Studio Longform Engine",
                    "=================================================================",
                    "",
                ]
                content = "\n".join(header) + "\n" + new_entry + "\n"
            else:
                content = "\n".join(existing_lines).strip() + "\n" + new_entry + "\n"

            tmp_credits = self.credits_file.parent / f"{self.credits_file.name}.tmp.{uuid.uuid4().hex}"
            try:
                tmp_credits.write_text(content, encoding="utf-8")
                os.replace(tmp_credits, self.credits_file)
            finally:
                if tmp_credits.exists():
                    tmp_credits.unlink(missing_ok=True)

    def write_credits_markdown(self, manifest: Any) -> Path:
        """Generate `export/credits.md` listing all assets needing attribution and other credits (D9.3)."""
        self.credits_md_file.parent.mkdir(parents=True, exist_ok=True)

        required_rows: List[Dict[str, Any]] = []
        other_rows: List[Dict[str, Any]] = []
        seen_keys: set[str] = set()

        for ch in getattr(manifest, "chapters", []) or []:
            for sh in getattr(ch, "shots", []) or []:
                if not (sh.rendered_clip or sh.asset_path):
                    continue
                src = str(sh.actual_source or "").strip()
                lic = str(getattr(sh, "attribution_license", None) or "").strip()
                author = str(getattr(sh, "attribution_author", None) or "").strip()
                title = str(getattr(sh, "attribution_title", None) or "").strip()
                url = str(getattr(sh, "attribution_url", None) or "").strip()
                needs_attr = bool(getattr(sh, "requires_attribution", False) or license_requires_attribution(lic))

                if not (lic or author or title or url):
                    continue
                dedup_k = f"{src}|{url or title}|{author}"
                if dedup_k in seen_keys:
                    for bucket in (required_rows, other_rows):
                        for row in bucket:
                            if row["_key"] == dedup_k and sh.shot_id not in row["shots"]:
                                row["shots"].append(sh.shot_id)
                    continue
                seen_keys.add(dedup_k)
                row_data = {
                    "_key": dedup_k,
                    "source": src or "-",
                    "title": title or "-",
                    "author": author or ("Pengguna" if src.lower() == "external_image" else "Unknown Creator"),
                    "license": lic or "-",
                    "url": url or "-",
                    "shots": [sh.shot_id],
                }
                if needs_attr:
                    required_rows.append(row_data)
                else:
                    other_rows.append(row_data)

        # Preserve BGM / legacy stock lines from credits.txt when present
        extra_lines: List[str] = []
        if self.credits_file.is_file():
            for ln in self.credits_file.read_text(encoding="utf-8", errors="ignore").splitlines():
                st_ln = ln.strip()
                if "[BGM]" in st_ln or "Audio" in st_ln:
                    extra_lines.append(st_ln)

        lines: List[str] = [
            f"# Visual & Audio Credits — {getattr(manifest, 'title', getattr(manifest, 'project_id', 'Project'))}",
            "",
            "Generated by **EasyFaceless Studio**. Please include items listed under *Attribution Required* in your video description.",
            "",
            "## Attribution Required (CC BY / CC BY-SA / NASA)",
            "",
        ]
        if required_rows:
            lines.extend([
                "| Shot(s) | Source | Title | Creator | License | URL |",
                "|---|---|---|---|---|---|",
            ])
            for r in required_rows:
                shots_s = ", ".join(r["shots"])
                url_md = f"[Source]({r['url']})" if r["url"].startswith("http") else r["url"]
                lines.append(
                    f"| `{shots_s}` | {r['source']} | {r['title']} | {r['author']} | {r['license']} | {url_md} |"
                )
            lines.append("")
        else:
            lines.extend([
                "_No assets requiring mandatory attribution were used in this project._",
                "",
            ])

        if other_rows or extra_lines:
            lines.extend([
                "## Other Licensed Sources & Background Music",
                "",
            ])
            for r in other_rows:
                shots_s = ", ".join(r["shots"])
                url_md = f" ({r['url']})" if r["url"] != "-" else ""
                title_part = f" {r['title']} —" if r["title"] and r["title"] != "-" else ""
                lines.append(
                    f"- **{shots_s}** [{r['source']}]:{title_part} {r['author']} — License: {r['license']}{url_md}"
                )
            for bl in extra_lines:
                lines.append(bl if bl.startswith("- ") else f"- {bl}")
            lines.append("")

        self.credits_md_file.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
        return self.credits_md_file

    def copy_credits_md_to(self, dest_dir: Path | str) -> Optional[Path]:
        """Copy credits.md into target output directory (e.g. MP4 export or CapCut draft)."""
        if not self.credits_md_file.is_file():
            return None
        target_dir = Path(dest_dir)
        target_dir.mkdir(parents=True, exist_ok=True)
        dest_file = target_dir / "credits.md"
        if dest_file.resolve() != self.credits_md_file.resolve():
            shutil.copyfile(self.credits_md_file, dest_file)
        return dest_file
