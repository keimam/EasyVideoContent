def get_ui_language() -> str:
    """Return effective canonical language ('id' or 'en') via single branding language module (E9.1)."""
    from app.services.branding.language import get_canonical_language

    return get_canonical_language()


def t(key: str, lang: Optional[str] = None, **kwargs: Any) -> str:
    """Retrieve localized string with formatting.

    :param key: Translation key string.
    :param lang: Explicit language code ('id' or 'en'), or None for automatic detection.
    :param kwargs: Optional formatting parameters.
    """
    effective_lang = (lang or get_ui_language()).lower()
    table = ID_TRANSLATIONS if effective_lang.startswith("id") else EN_TRANSLATIONS

    text = table.get(key)
    if text is None:
        # Fallback to alternative language or key itself
        alt_table = EN_TRANSLATIONS if effective_lang.startswith("id") else ID_TRANSLATIONS
        text = alt_table.get(key, key)

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
